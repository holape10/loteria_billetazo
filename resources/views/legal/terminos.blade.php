            <section>
                <h2 class="text-xl font-bold text-dorado-300 mb-3">1. Requisitos de participación</h2>
                <p class="mb-2">Para participar en los sorteos de "El Billetazo", el usuario debe cumplir obligatoriamente con lo siguiente:</p>
                <ul class="list-disc list-inside space-y-1">
                    <li><span class="font-semibold text-white">Edad mínima:</span> Ser mayor de 18 años.</li>
                    <li><span class="font-semibold text-white">Identificación:</span> Ser persona natural con Documento Nacional de Identidad (DNI) vigente.</li>
                    <li><span class="font-semibold text-white">Residencia:</span> Residir dentro del territorio de la República del Perú.</li>
                    <li><span class="font-semibold text-white">Medio de pago:</span> Contar con una cuenta bancaria o billetera digital nacional (Yape, Plin o transferencia) a su nombre para comprar jugadas y recibir premios.</li>
                    <li><span class="font-semibold text-white">Registro:</span> Haber completado el formulario de inscripción con datos reales y haber enviado el comprobante de pago correspondiente.</li>
                </ul>
            </section>

            <section>
                <h2 class="text-xl font-bold text-dorado-300 mb-3">2. Mecánica del juego y apuestas</h2>
                <ul class="list-disc list-inside space-y-1">
                    <li><span class="font-semibold text-white">Selección de números:</span> Cada jugada consiste en la selección libre de seis (6) números únicos por parte del participante, dentro de un rango del uno (1) al sesenta (60).</li>
                    <li><span class="font-semibold text-white">Naturaleza de la jugada:</span> Los números registrados son personales, fijos e intransferibles para el sorteo de la semana.</li>
                    <li><span class="font-semibold text-white">Política de no devolución:</span> Una vez que el pago de la jugada ha sido validado, no se realizarán devoluciones de dinero ni cambios de números bajo ninguna circunstancia.</li>
                    <li><span class="font-semibold text-white">El Sorteo:</span> Los sorteos se realizarán de manera fija todos los domingos a las 4:00 p. m. (hora de Perú). Se extraerán seis (6) números ganadores de forma aleatoria. Los resultados oficiales se publicarán inmediatamente después en los canales y redes oficiales de "El Billetazo".</li>
                </ul>
            </section>

            <section>
                <h2 class="text-xl font-bold text-dorado-300 mb-3">3. Estructura de premios y reparto equitativo</h2>
                <p class="mb-2">Los premios se asignan según el número de aciertos obtenidos en una misma jugada. Si existen dos (2) o más ganadores en cualquiera de las categorías de aciertos, el monto total asignado a esa categoría se dividirá y repartirá en partes estrictamente iguales entre el número de ganadores.</p>
                <ul class="list-disc list-inside space-y-1">
                    <li><span class="font-semibold text-white">Categoría de 4 Aciertos:</span> Premio de S/ 50.00. Si hay 2 o más ganadores, el pozo se divide equitativamente entre ellos.</li>
                    <li><span class="font-semibold text-white">Categoría de 5 Aciertos:</span> Premio de S/ 100.00. Si hay 2 o más ganadores, el pozo se divide equitativamente entre ellos.</li>
                    <li><span class="font-semibold text-white">Categoría de 6 Aciertos (Pozo Máximo):</span> Premio base de S/ 1,000.00 más el Pozo Acumulado a la fecha. Si hay 2 o más ganadores, la suma total acumulada se divide equitativamente entre ellos.</li>
                    <li><span class="font-semibold text-white">Dinámica del Pozo Acumulado:</span> Si en un sorteo dominical no hay ganadores con 6 aciertos, el pozo se incrementará en S/ 200.00 semanales para el siguiente domingo. Una vez que alguien lo gane, el pozo vuelve a su base de S/ 1,000.00.</li>
                </ul>
            </section>

            <section>
                <h2 class="text-xl font-bold text-dorado-300 mb-3">4. Condiciones de pago y validación</h2>
                <ul class="list-disc list-inside space-y-1">
                    <li><span class="font-semibold text-white">Acreditación del premio:</span> Los premios validados se pagarán mediante transferencia bancaria o billetera digital en un plazo máximo de 72 horas hábiles posteriores al sorteo. El titular de la cuenta receptora debe coincidir con el DNI registrado en la jugada.</li>
                    <li><span class="font-semibold text-white">Caducidad del cobro:</span> El derecho a reclamar y cobrar cualquier premio expira de forma automática a los 30 días calendario del sorteo. Pasado este tiempo, el participante pierde el derecho sobre el premio.</li>
                    <li><span class="font-semibold text-white">Responsabilidad de datos:</span> El participante es el único responsable de ingresar datos correctos y revisar los resultados. "El Billetazo" no se hace responsable por transferencias fallidas debido a errores en el número de cuenta o número de celular brindado por el usuario.</li>
                </ul>
            </section>

